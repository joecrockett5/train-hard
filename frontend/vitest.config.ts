import { defineConfig } from 'vitest/config';
import { svelte } from '@sveltejs/vite-plugin-svelte';
import { svelteTesting } from '@testing-library/svelte/vite';

/**
 * Two projects, because the suite has two kinds of test in it.
 *
 * The domain modules -- units, the chart's arithmetic, tag colours, the
 * mappers -- are plain TypeScript and run in node, which is fast and needs no
 * DOM. The handful of component tests need one, so they run under jsdom with
 * the Svelte plugin loaded.
 */
export default defineConfig({
	plugins: [svelte({ hot: false }), svelteTesting()],
	resolve: {
		conditions: ['browser'],
		alias: {
			$lib: new URL('./src/lib', import.meta.url).pathname,
			$ui: new URL('./src/lib/ui', import.meta.url).pathname,
			$components: new URL('./src/lib/components', import.meta.url).pathname,
			// Generated by SvelteKit during a build, so unresolvable here.
			'$env/dynamic/private': new URL('./src/lib/server/env-stub.ts', import.meta.url).pathname,
			'$service-worker': new URL('./src/lib/service-worker-stub.ts', import.meta.url).pathname
		}
	},
	test: {
		include: ['src/**/*.test.ts'],
		environment: 'node',
		environmentMatchGlobs: [['src/**/*.dom.test.ts', 'jsdom']]
	}
});
